create table if not exists public.orders (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    customer_first_name text not null,
    customer_last_name text not null,
    address text not null,
    city text not null,
    country text not null,
    postal_code text not null,
    phone text not null,
    items jsonb not null default '[]'::jsonb,
    subtotal numeric not null default 0,
    status text not null default 'pending'
        check (status in ('pending', 'processing', 'shipped', 'delivered', 'cancelled'))
);

alter table public.orders enable row level security;
revoke all on table public.orders from anon, authenticated;
grant insert on table public.orders to anon, authenticated;
grant select, update, delete on table public.orders to authenticated;

drop policy if exists "Customers can create orders" on public.orders;
create policy "Customers can create orders"
on public.orders
for insert
to anon, authenticated
with check (true);

drop policy if exists "Signed-in users can view orders" on public.orders;
create policy "Signed-in users can view orders"
on public.orders
for select
to authenticated
using (true);

drop policy if exists "Signed-in users can update orders" on public.orders;
create policy "Signed-in users can update orders"
on public.orders
for update
to authenticated
using (true)
with check (true);

drop policy if exists "Signed-in users can delete orders" on public.orders;
create policy "Signed-in users can delete orders"
on public.orders
for delete
to authenticated
using (true);
